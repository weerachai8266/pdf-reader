// Builds src/img/icons.svg: one <symbol id="i-NAME"> per icon the UI uses,
// taken from lucide-static (ISC). Re-run after adding a name below:
//   node tools/make-icon-sprite.js

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ICONS = [
    'panel-left', 'folder-open', 'file-plus-2', 'save', 'printer',
    'chevron-left', 'chevron-right', 'chevron-up', 'chevron-down', 'zoom-in', 'zoom-out',
    'mouse-pointer-2', 'highlighter', 'message-square-text', 'signature',
    'rectangle-horizontal', 'eraser', 'scan-text', 'search',
    'rotate-ccw', 'rotate-cw', 'trash-2',
    'pen-tool', 'shield-check', 'shield-alert', 'shield-x', 'git-compare', 'x', 'files',
];

const root = path.join(__dirname, '..');
const pkg = require(path.join(root, 'node_modules/lucide-static/package.json'));
const symbols = ICONS.map((name) => {
    const svg = fs.readFileSync(path.join(root, 'node_modules/lucide-static/icons', `${name}.svg`), 'utf8');
    const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
        .split('\n').map((l) => l.trim()).filter(Boolean).join('');
    return `  <symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
});

const out = `<!-- Icons from Lucide v${pkg.version} (https://lucide.dev), ISC License,
     Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).
     All other copyright (c) for Lucide are held by Lucide Contributors 2022.
     Generated by tools/make-icon-sprite.js; do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
${symbols.join('\n')}
</svg>
`;
fs.writeFileSync(path.join(root, 'src/img/icons.svg'), out);
console.log(`src/img/icons.svg: ${ICONS.length} icons`);
